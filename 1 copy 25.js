const findMax = (numbers) => {
  // 1. نفترض أن أول رقم هو الأكبر (كنقطة بداية)
  // (نستخدم let لأنه سيتغير)
  let max = numbers[0];
  
  // 2. نمر على "باقي" الأرقام
  for (const num of numbers) {
    
    // 3. هل الرقم الحالي (num) أكبر من (max) الذي نحتفظ به؟
    if (num > max) {
      // 4. إذا نعم، نحدّث max ليصبح هو الرقم الحالي
      max = num;
    }
  }
  
  // 5. بعد انتهاء اللوب، نرجع أكبر رقم وجدناه
  return max;
};